CREATE TABLE orders (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 order_no VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
 item_code VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
 qty DECIMAL(18,4) NOT NULL,
 CONSTRAINT chk_orders_qty CHECK(qty > 0)
) ENGINE=InnoDB;
CREATE TABLE production_plans (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT NOT NULL,
 item_code VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
 qty DECIMAL(18,4) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'WAITING',
 CONSTRAINT fk_plan_order FOREIGN KEY(order_id) REFERENCES orders(id),
 CONSTRAINT chk_plan_qty CHECK(qty > 0),
 CONSTRAINT chk_plan_status CHECK(status IN ('WAITING','SCHEDULED','COMPLETED'))
) ENGINE=InnoDB;
CREATE TABLE process_details (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 plan_id BIGINT NOT NULL,
 step_no INT NOT NULL,
 process_code VARCHAR(32) NOT NULL,
 qty DECIMAL(18,4) NOT NULL,
 CONSTRAINT fk_detail_plan FOREIGN KEY(plan_id) REFERENCES production_plans(id),
 CONSTRAINT chk_detail_qty CHECK(qty > 0)
) ENGINE=InnoDB;
